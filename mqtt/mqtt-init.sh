# Writes the services' password file and ACL from .env, on every start.
#   MQTT_SERVER_PASSWORD   password of the internal "server" account (listener 1883)
#
# Devices have no accounts here: they authenticate with a client certificate
# on 8883 (mosquitto.conf); their ACL (acl-devices) is rendered by mqtt-run.sh
# from the operator's block list.
set -eu

dir=/mosquitto/auth
tmpd=$(mktemp -d)
pw="$tmpd/passwd"
acl="$tmpd/acl-services"

[ -n "${MQTT_SERVER_PASSWORD:-}" ] || { echo "MQTT_SERVER_PASSWORD is empty" >&2; exit 1; }
mosquitto_passwd -b -c "$pw" server "$MQTT_SERVER_PASSWORD"
# svc/#: the retained block list the leader engine publishes (svc/blocked);
# registry/#: the service layer's device registry (read by the leader engine;
# written by scripts/registry.sh in PKI_MODE=own, where there is no layer).
printf '# generated by mqtt-init.sh — do not edit\n\nuser server\ntopic readwrite dev/#\ntopic readwrite svc/#\ntopic read registry/#\ntopic write registry/#\n' > "$acl"

# Mosquitto runs as uid 1883 and warns about (future versions: refuse)
# files it does not own or that others can read.
chown 1883:1883 "$pw" "$acl" && chmod 0600 "$pw" "$acl"
mv "$pw" "$dir/passwd"
mv "$acl" "$dir/acl-services"
rm -f "$dir/acl"   # the per-device ACL of the password era (before 13.11.2026)
rmdir "$tmpd"
echo "password file and service ACL written"
