# Runs Mosquitto and reloads it (SIGHUP) when the services' password file or
# an ACL changes:
#   - mqtt-init rewrote passwd / acl-services (a new MQTT_SERVER_PASSWORD);
#   - the operator blocked or unblocked a device (task A5): the leader engine
#     publishes the retained list on svc/blocked ("v1 <id> <id> ..."); a
#     subscriber here renders it into acl-devices.
# Blocked devices keep their TLS connection but may neither publish nor
# receive anything (a deny section before the device pattern).
set -eu
CONF=${MQTT_CONF:-/mosquitto/config/mosquitto.conf}
AUTH=${MQTT_AUTH_DIR:-/mosquitto/auth}
BLOCKED="$AUTH/blocked"

render() {
  # $1: the list as published; only valid device ids are taken (no ACL injection).
  tmp="$AUTH/acl-devices.tmp"
  printf '# generated by mqtt-run.sh from svc/blocked — do not edit\n' > "$tmp"
  for id in $1; do
    case "$id" in v1) continue ;; esac
    case "$id" in *[!a-z0-9-]*|-*|'') echo "mqtt-run: ignoring blocked id '$id'" >&2; continue ;; esac
    printf '\nuser %s\ntopic deny dev/%s/#\n' "$id" "$id" >> "$tmp"
  done
  # the service layer (reserved CN "layer", certificate under this cloud's root):
  # writes the device registry, nothing else (its pattern subtree dev/layer/# is no device's)
  printf '\nuser layer\ntopic write registry/#\n' >> "$tmp"
  printf '\n# every device: its own subtree only (user name = certificate CN)\npattern readwrite dev/%%u/#\n' >> "$tmp"
  chown 1883:1883 "$tmp" && chmod 0600 "$tmp"
  mv "$tmp" "$AUTH/acl-devices"
}

# Start with the list last seen (the broker's own retained copy comes back
# from persistence and is read again below).
render "$(cat "$BLOCKED" 2>/dev/null || true)"

/usr/sbin/mosquitto -c "$CONF" &
pid=$!

watch_blocked() {
  while kill -0 "$pid" 2>/dev/null; do
    mosquitto_sub -h 127.0.0.1 -p 1883 -u server -P "${MQTT_SERVER_PASSWORD:-}" -i "mqtt-run-$$" \
      -t svc/blocked -q 1 2>/dev/null |
    while IFS= read -r line; do
      printf '%s\n' "$line" > "$BLOCKED.tmp" && mv "$BLOCKED.tmp" "$BLOCKED"
      render "$line"
    done
    sleep 2
  done
}
watch_blocked &
wpid=$!
trap 'kill -TERM "$pid" "$wpid" 2>/dev/null; wait "$pid"; exit 0' TERM INT

sum() { cat "$AUTH/passwd" "$AUTH/acl-services" "$AUTH/acl-devices" 2>/dev/null | md5sum; }
last=$(sum)
while kill -0 "$pid" 2>/dev/null; do
  sleep 2 &
  wait $! || true
  now=$(sum)
  if [ "$now" != "$last" ]; then
    kill -HUP "$pid" && echo "mqtt-run: password file or ACL changed, broker reloaded"
    last=$now
  fi
done
wait "$pid"
